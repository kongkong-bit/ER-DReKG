from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def cypher_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    processed = root / "data/processed/top10_kg"
    identity = read_rows(processed / "top10_external_identity.csv")
    evidence = read_rows(processed / "top10_external_records.csv")
    claims = read_rows(processed / "top10_claims.csv")
    paths = read_rows(processed / "top10_mechanism_paths.csv")
    run_id = "top10_kg_v1"
    lines = [
        "// Generated by scripts/plan_top10_neo4j_import.py; review before any write.",
        "// Namespace is isolated under Top10* labels and top10_kg_v1 properties.",
        "CREATE CONSTRAINT top10_drug_key IF NOT EXISTS FOR (n:Top10Drug) REQUIRE n.pert_id IS UNIQUE;",
        "CREATE CONSTRAINT top10_evidence_key IF NOT EXISTS FOR (n:Top10Evidence) REQUIRE n.evidence_key IS UNIQUE;",
    ]
    for row in identity:
        props = {"pert_id": row["pert_id"], "name": row["pert_iname"], "mapping_status": row["mapping_status"], "chembl_id": row.get("chembl_id", ""), "pubchem_cid": row.get("pubchem_cid", ""), "inchikey": row.get("inchikey", ""), "run_id": run_id}
        lines.append(f"MERGE (d:Top10Drug {{pert_id: {cypher_string(row['pert_id'])}}}) SET d += {json.dumps(props, ensure_ascii=False)};")
    for row in evidence:
        key = f"{row['pert_id']}::{row['source']}::{row['source_record_id']}"
        props = {"evidence_key": key, "pert_id": row["pert_id"], "source": row["source"], "source_record_id": row["source_record_id"], "snapshot_path": row["snapshot_path"], "evidence_type": row["evidence_type"], "validation_status": row["validation_status"], "run_id": run_id}
        lines.append(f"MERGE (e:Top10Evidence {{evidence_key: {cypher_string(key)}}}) SET e += {json.dumps(props, ensure_ascii=False)} WITH e MATCH (d:Top10Drug {{pert_id: {cypher_string(row['pert_id'])}}}) MERGE (d)-[:HAS_EXTERNAL_EVIDENCE {{run_id: {cypher_string(run_id)}}}]->(e);")
    for row in claims:
        props = {"claim_id": row["claim_id"], "subject_id": row["subject_id"], "predicate": row["predicate"], "object_id": row["object_id"], "status": row["status"], "source_record_id": row["source_record_id"], "run_id": run_id}
        lines.append(f"MERGE (c:Top10Claim {{claim_id: {cypher_string(row['claim_id'])}}}) SET c += {json.dumps(props, ensure_ascii=False)};")
    for row in paths:
        props = {"path_id": row["path_id"], "pert_id": row["pert_id"], "target_gene_id": row["target_gene_id"], "pathway_id": row["pathway_id"], "pathway_label": row["pathway_label"], "status": row["status"], "run_id": run_id}
        lines.append(f"MERGE (p:Top10MechanismPath {{path_id: {cypher_string(row['path_id'])}}}) SET p += {json.dumps(props, ensure_ascii=False)} WITH p MATCH (d:Top10Drug {{pert_id: {cypher_string(row['pert_id'])}}}) MERGE (d)-[:HAS_MECHANISM_PATH {{run_id: {cypher_string(run_id)}}}]->(p);")
    lines.append("// No database write is performed by this script. Apply only after backup, credential verification, and human review.")
    plan_path = root / "reports/top10_kg/neo4j_import_plan.cypher"
    plan_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    manifest = {"run_id": run_id, "write_performed": False, "requires": ["backup_path", "NEO4J_URI", "NEO4J_USER", "NEO4J_PASSWORD", "human_review"], "drug_nodes": len(identity), "evidence_nodes": len(evidence), "claim_nodes": len(claims), "path_nodes": len(paths), "failed_or_skipped_sources_imported": 0, "cypher_path": str(plan_path)}
    (root / "reports/top10_kg/neo4j_import_plan.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(manifest, ensure_ascii=False))


if __name__ == "__main__":
    main()
